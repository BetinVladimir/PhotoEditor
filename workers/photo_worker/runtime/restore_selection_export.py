@dataclass(frozen=True)
class RestoreSelectionExport:
    fixture_sha256: str
    selection: object
    export: object


def selection_export_descriptor(replay,selection_target,preset_id,export_key,binding,selection,apply_target,apply_ticket,
        download_target,*,params,intent_key,scratch_root,maximum_seconds,alpha_dtype='uint16'):
    if (not isinstance(selection_target,RestoreSelectionTarget)
            or selection_target.tenant_id!=apply_target.tenant_id or selection_target.origin!=apply_target.origin
            or selection_target.authorization!=apply_target.authorization
            or selection_target.collection_id!=apply_ticket.output_collection_id
            or type(selection_target.collection_revision) is not int or not 1<=selection_target.collection_revision<=9007199254740991
            or len({selection_target.idempotency_key,export_key,intent_key})!=3):
        raise ValueError('RESTORE_SELECTION_EXPORT_INSTALLATION')
    template=RestoreExportTarget(selection_target.origin,selection_target.tenant_id,selection_target.collection_id,
        preset_id,export_key,selection_target.authorization)
    descriptor=export_fixture_descriptor(replay,template,binding,selection,apply_target,apply_ticket,download_target,
        params=params,intent_key=intent_key,scratch_root=scratch_root,maximum_seconds=maximum_seconds,alpha_dtype=alpha_dtype)
    # Snapshot UUID is generated by the server; bind the native selection
    # request and independently known digest instead of predicting its UUID.
    descriptor.pop('selection_snapshot_id');descriptor.pop('request_sha256')
    descriptor.update(schema_version='restore-selection-export-fixture/v1',
        selection_collection_id=str(selection_target.collection_id),selection_item_id=str(selection_target.item_id),
        selection_request_sha256=sha256(selection_request_body(selection_target)).hexdigest(),
        selection_key_sha256=sha256(selection_target.idempotency_key.encode()).hexdigest())
    return descriptor


def run_pinned_selection_export(replay,fixture_sha256,connection,client,buckets,selection_target,preset_id,export_key,
        binding,selection,apply_target,apply_ticket,download_target,*,params,intent_key,scratch_root,maximum_seconds,
        pepper,tls_context,assert_installed_fixture,check_active,alpha_dtype='uint16'):
    if (not isinstance(fixture_sha256,str) or re.fullmatch('[0-9a-f]{64}',fixture_sha256) is None
            or type(pepper) is not bytes or len(pepper)<32
            or not callable(assert_installed_fixture) or not callable(check_active)):
        raise ValueError('RESTORE_SELECTION_EXPORT_INSTALLATION')
    descriptor=selection_export_descriptor(replay,selection_target,preset_id,export_key,binding,selection,
        apply_target,apply_ticket,download_target,params=params,intent_key=intent_key,scratch_root=scratch_root,
        maximum_seconds=maximum_seconds,alpha_dtype=alpha_dtype)
    if sha256(canonical_bytes(descriptor)).hexdigest()!=fixture_sha256:
        raise ValueError('RESTORE_SELECTION_EXPORT_FIXTURE_PIN')
    deadline=monotonic()+maximum_seconds
    def guard():
        require_restore_fixture(check_active,assert_installed_fixture)
        if monotonic()>=deadline:raise ValueError('RESTORE_SELECTION_EXPORT_TIMEOUT')
    def scope(*_):guard()
    validation=dict(tls_context=tls_context,assert_fixture_scope=scope,check_active=guard)
    validate_fixture_selection(selection_target,**validation)
    validate_preview_download_installation(download_target,**validation)
    template=RestoreExportTarget(selection_target.origin,selection_target.tenant_id,selection_target.collection_id,
        preset_id,export_key,selection_target.authorization)
    validate_fixture_export(template,**validation)
    validate_fixture_download_intent(RestoreDownloadIntentTarget(template.origin,template.tenant_id,
        template.selection_snapshot_id,1,intent_key,template.authorization),**validation)
    root=Path(scratch_root)
    if not root.is_absolute() or root.resolve(strict=True)!=root or not root.is_dir():
        raise ValueError('RESTORE_EXPORT_SCRATCH_ROOT')
    guard();source=verify_fixture_legacy_working_image(connection,client,buckets,apply_target,binding,apply_ticket,
        expected_database=replay.database,assert_fixture_scope=scope,check_active=guard,alpha_dtype=alpha_dtype)
    width,height=_dimensions(source.width,source.height,params)
    verify_export_geometry(params,source,source.result.asset_version_id,width,height,
        source.alpha is not None and params.alpha=='preserve')
    registered=create_fixture_selection(connection,selection_target,binding.actor_id,source.result,
        expected_database=replay.database,tls_context=tls_context,assert_installed_fixture=guard,check_active=guard)
    if registered.ticket.digest!=selection.snapshot_digest:raise ValueError('RESTORE_SELECTION_EXPORT_DIGEST')
    target=RestoreExportTarget(template.origin,template.tenant_id,registered.ticket.snapshot_id,preset_id,export_key,template.authorization)
    completed=run_fixture_export(connection,client,buckets,target,binding,selection,apply_target,apply_ticket,download_target,
        expected_database=replay.database,params=params,intent_key=intent_key,scratch_root=scratch_root,
        maximum_seconds=maximum_seconds,pepper=pepper,tls_context=tls_context,
        assert_installed_fixture=guard,check_active=guard,alpha_dtype=alpha_dtype)
    final=observe_fixture_selection(connection,selection_target,registered.ticket,binding.actor_id,source.result,
        expected_database=replay.database,check_active=guard)
    if final!=registered.registration:raise ValueError('RESTORE_SELECTION_EXPORT_CHANGED')
    guard();return RestoreSelectionExport(fixture_sha256,registered,completed)
