type overlay struct {
	base  fs.FS
	files fstest.MapFS
}

func (o overlay) Open(name string) (fs.File, error) {
	if _, ok := o.files[name]; ok {
		return o.files.Open(name)
	}
	return o.base.Open(name)
}
func sha(b []byte) string { v := sha256.Sum256(b); return hex.EncodeToString(v[:]) }
func run() error {
	if os.Getenv("CONFIRM_AUTHORED_RENDER_2650") != "2649-to-2650-reviewed-empty-installations" {
		return errors.New("explicit2650 confirmation required")
	}
	const path = "migrations/02650_authored_render_versioned_worker_admission.sql"
	// Filename and source pins are generated by the preparation script below.
	raw, e := migrations.FS.ReadFile(path)
	if e != nil {
		return e
	}
	if sha(raw) != "cb6529dbb07cff6333cca0b9a4a7a721b3b8e07207194dfbaf5b0d98e00257ef" {
		return errors.New("migration source drift")
	}
	if e = migrations.ValidateBundle(migrations.FS); e != nil {
		return e
	}
	before, e := os.ReadFile("/Users/freelancer/Documents/PhotoEditor/work/authored-render-main-2650-r1/guards-before.sql")
	if e != nil {
		return e
	}
	after, e := os.ReadFile("/Users/freelancer/Documents/PhotoEditor/work/authored-render-main-2650-r1/guards-after.sql")
	if e != nil {
		return e
	}
	if sha(before) != "ce23b334a783fa145977f3017437eb65db75532747cf50a74a32ea74a39e7085" || sha(after) != "151648f47223627b6579551dcda16ceae02d1e1644db085e6451786540e12677" {
		return errors.New("operator guards drift")
	}
	// Original complete migration bytes remain untouched inside derived source.
	up := "-- +goose Up\n"
	down := "-- +goose Down"
	if strings.Count(string(raw), up) != 1 || strings.Count(string(raw), down) != 1 {
		return errors.New("goose anchor count")
	}
	derived := strings.Replace(string(raw), up, up+"-- +goose StatementBegin\n"+string(before)+"\n-- +goose StatementEnd\n", 1)
	derived = strings.Replace(derived, down, "-- +goose StatementBegin\n"+string(after)+"\n-- +goose StatementEnd\n"+down, 1)
	if strings.Contains(derived, "-- +goose NO TRANSACTION") {
		return errors.New("transaction required")
	}
	db, e := sql.Open("pgx", os.Getenv("DATABASE_URL"))
	if e != nil {
		return errors.New("database configuration failed")
	}
	defer db.Close()
	db.SetMaxOpenConns(1)
	ctx := context.Background()
	var head int64
	if e = db.QueryRowContext(ctx, "SELECT max(version_id)FROM goose_db_version WHERE is_applied").Scan(&head); e != nil {
		return e
	}
	if head != 2649 {
		return errors.New("exact head2649 required")
	}
	if e = migrations.ValidateInstalledSecurity(ctx, db); e != nil {
		return e
	}
	goose.SetBaseFS(overlay{migrations.FS, fstest.MapFS{path: &fstest.MapFile{Data: []byte(derived)}}})
	if e = goose.SetDialect("postgres"); e != nil {
		return e
	}
	if e = goose.UpTo(db, "migrations", 2650); e != nil {
		return migrations.SummarizeError(e)
	}
	if e = migrations.ValidateInstalledSecurity(ctx, db); e != nil {
		return e
	}
	if e = db.QueryRowContext(ctx, "SELECT max(version_id)FROM goose_db_version WHERE is_applied").Scan(&head); e != nil {
		return e
	}
	if head != 2650 {
		return errors.New("posthead mismatch")
	}
	fmt.Println("PINNED_TRANSACTION_GUARDED_GOOSE_2649_TO_2650_APPLIED")
	return nil
}
func main() {
	if e := run(); e != nil {
		var pg *pgconn.PgError
		if errors.As(e, &pg) {
			fmt.Fprintf(os.Stderr, "OPERATOR_SQLSTATE=%s ROUTINE=%s POSITION=%d\n", pg.Code, pg.Routine, pg.Position)
			if strings.HasPrefix(pg.Message, "OPERATOR2650_") {
				fmt.Fprintln(os.Stderr, pg.Message)
			}
		}
		fmt.Fprintf(os.Stderr, "OPERATOR_FAILED_CLASS=%T\n", e)
		os.Exit(1)
	}
}
