from pathlib import Path

ROOT=Path(__file__).parents[2]

def test_sqlc_is_pinned_generated_and_used():
    script=(ROOT/'scripts/generate-sqlc.sh').read_text()
    config=(ROOT/'sqlc.yaml').read_text()
    service=(ROOT/'backend/internal/exportpreset/service.go').read_text()
    generated=(ROOT/'backend/internal/db/generated/export_presets.sql.go').read_text()
    assert 'sqlc@v1.31.1' in script and '--check' in script
    assert 'sql_package: "pgx/v5"' in config
    assert 'generated.New(tx).ListExportPresets' in service
    assert 'generated.New(tx).CreateExportPreset' in service
    assert 'Code generated by sqlc' in generated and 'sqlc v1.31.1' in generated

def test_analysis_schema_matches_runtime_export_presets_columns():
    schema=(ROOT/'backend/db/sqlc-schema.sql').read_text()
    migration=(ROOT/'backend/db/migrations/00008_delivery.sql').read_text()
    for column in ('id','created_at','tenant_id','name','revision','config','config_hash','archived_at'):
        assert column in schema and f'"{column}"' in migration or column in {'id','created_at','tenant_id'}
