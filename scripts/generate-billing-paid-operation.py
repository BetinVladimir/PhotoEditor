#!/usr/bin/env python3
"""Generate the guarded forward-only paid operation funding correction."""
from pathlib import Path
import argparse,re
ROOT=Path(__file__).resolve().parents[1]
def render(body=None):
    if body is None:body=(ROOT/'docs/billing/contracts/paid-operation-funding.sql').read_text()
    body=re.sub(r'(CREATE (?:OR REPLACE )?FUNCTION photo\.[\s\S]*?\n(?:END )?\$\$;)',r'-- +goose StatementBegin\n\1\n-- +goose StatementEnd',body)
    body=re.sub(r'(DO \$\$[\s\S]*?END \$\$;)',r'-- +goose StatementBegin\n\1\n-- +goose StatementEnd',body)
    return '-- Generated by scripts/generate-billing-paid-operation.py; DO NOT EDIT.\n'+body+"\n-- +goose Down\n-- +goose StatementBegin\nDO $$ BEGIN RAISE EXCEPTION 'Forward-only paid operation funding migration'; END $$;\n-- +goose StatementEnd\n"
if __name__=='__main__':
    p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');args=p.parse_args();path=ROOT/'backend/db/migrations/02608_billing_paid_operation_funding.sql'
    if args.check:
        if path.read_text()!=render():raise SystemExit('Paid operation funding migration drift')
    else:path.write_text(render())
