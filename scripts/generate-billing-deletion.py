#!/usr/bin/env python3
"""Generate new deletion-step migrations without rewriting historical legal SQL."""
import argparse
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
SCHEMA = '02669_billing_deletion_steps.sql'
FUNCTIONS = '02670_billing_deletion_step_functions.sql'
TYPES = {'uuid', 'text', 'bigint', 'bytea', 'timestamptz'}
IDENT = re.compile(r'^[a-z][a-z0-9_]{0,62}$')


def ident(value):
    if not isinstance(value, str) or not IDENT.fullmatch(value):
        raise ValueError('Invalid deletion identifier')
    return value


def render(root=ROOT):
    source = root / 'docs/billing/contracts'
    tables = json.loads((source / 'deletion-steps-tables.json').read_text())
    functions = json.loads((source / 'deletion-steps-functions.json').read_text())
    if tables['schema_version'] != 1 or functions['schema_version'] != 1:
        raise ValueError('Unsupported deletion contract version')
    header = '-- Generated by scripts/generate-billing-deletion.py; DO NOT EDIT.\n-- +goose Up\n'
    refusal = "\n-- +goose Down\n-- +goose StatementBegin\nDO $$ BEGIN RAISE EXCEPTION 'Forward-only deletion worker migration';END $$;\n-- +goose StatementEnd\n"
    ddl = [header]
    seen = set()
    for table in tables['tables']:
        name = ident(table['name'])
        if name in seen: raise ValueError('Duplicate deletion table')
        seen.add(name)
        if table['acl'] != {'photo_fn_owner': ['SELECT', 'INSERT', 'UPDATE']} or table['rls'] != 'force_trusted_functions':
            raise ValueError('Unsafe deletion table ACL')
        columns = []
        names = set()
        for column in table['columns']:
            key = ident(column['name'])
            if key in names or column['type'] not in TYPES: raise ValueError('Invalid deletion column')
            names.add(key)
            value = key + ' ' + column['type']
            if not column.get('nullable', True): value += ' NOT NULL'
            if 'default' in column: value += ' DEFAULT ' + column['default']
            columns.append(value)
        if not set(table['primary_key']) <= names: raise ValueError('Invalid deletion primary key')
        columns += ['PRIMARY KEY (' + ','.join(ident(x) for x in table['primary_key']) + ')'] + table['constraints']
        ddl.append('CREATE TABLE photo.' + name + '(\n ' + ',\n '.join(columns) + '\n);')
        ddl.extend(x + ';' for x in table['indexes'])
        ddl.extend(['REVOKE ALL ON photo.' + name + ' FROM PUBLIC;',
                    'ALTER TABLE photo.' + name + ' ENABLE ROW LEVEL SECURITY;',
                    'ALTER TABLE photo.' + name + ' FORCE ROW LEVEL SECURITY;',
                    'CREATE POLICY deletion_steps ON photo.' + name + ' TO photo_fn_owner USING(true) WITH CHECK(true);',
                    'GRANT SELECT,INSERT,UPDATE ON photo.' + name + ' TO photo_fn_owner;'])
    body = (source / 'deletion-steps-functions.sql').read_text()
    chunks = re.split(r'(?=CREATE FUNCTION photo\.)', body)
    code = [header, chunks[0]]
    parsed = []
    for chunk in chunks[1:]:
        match = re.match(r'CREATE FUNCTION photo\.([a-z_]+)\(([^)]*)\)', chunk)
        if not match: raise ValueError('Invalid deletion declaration')
        name, args = match.groups()
        signature = name + '(' + ','.join(arg.strip().split()[1] for arg in args.split(',')) + ')'
        entry = next((f for f in functions['functions'] if f['signature'] == signature), None)
        if entry is None or entry['owner'] != 'photo_fn_owner' or entry['execute_roles'] != ['photo_maintenance']:
            raise ValueError('Unsafe deletion function ACL')
        if 'SECURITY DEFINER SET search_path=pg_catalog,photo' not in chunk:
            raise ValueError('Unsafe deletion function configuration')
        if len(chunk.splitlines()) > 80: raise ValueError('Deletion function exceeds R31')
        code.extend(['-- +goose StatementBegin\n' + chunk.strip() + '\n-- +goose StatementEnd',
                     'ALTER FUNCTION photo.' + signature + ' OWNER TO photo_fn_owner;',
                     'REVOKE ALL ON FUNCTION photo.' + signature + ' FROM PUBLIC;',
                     'GRANT EXECUTE ON FUNCTION photo.' + signature + ' TO photo_maintenance;'])
        parsed.append(signature)
    if len(parsed) != len(set(parsed)) or set(parsed) != {f['signature'] for f in functions['functions']}:
        raise ValueError('Deletion function inventory mismatch')
    return {SCHEMA: '\n\n'.join(ddl) + refusal, FUNCTIONS: '\n\n'.join(code) + refusal}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for name, content in render().items():
        path = ROOT / 'backend/db/migrations' / name
        if args.check:
            if not path.exists() or path.read_text() != content:
                raise SystemExit('Deletion generated migration drift: ' + name)
        elif path.exists() and path.read_text() != content:
            raise SystemExit('Refusing to overwrite existing migration: ' + name)
        else:
            path.write_text(content)


if __name__ == '__main__': main()
