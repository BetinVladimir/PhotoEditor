#!/usr/bin/env python3
"""Extend the V21 GC and tenant purge functions for V22-owned rows."""

from pathlib import Path
import argparse


ROOT = Path(__file__).resolve().parents[1]
SCAFFOLDS = ROOT / "backend/db/v2-scaffolds"
OUTPUT = SCAFFOLDS / "00197_gc_purge.sql"


def replace_once(body: str, old: str, new: str) -> str:
    if body.count(old) != 1:
        raise ValueError(f"Expected one source anchor: {old[:80]}")
    return body.replace(old, new, 1)


def render() -> str:
    gc = (SCAFFOLDS / "00196_gc_refs.sql").read_text()
    gc = replace_once(gc, "CREATE FUNCTION photo.v2_artifact_has_references",
                      "CREATE OR REPLACE FUNCTION photo.v2_artifact_has_references")
    gc = replace_once(
        gc,
        "  OR EXISTS(SELECT FROM photo.model_qualifications x WHERE x.tenant_id=p_tenant AND x.report_artifact_id=p_artifact)",
        "  OR EXISTS(SELECT FROM photo.model_qualifications x WHERE x.tenant_id=p_tenant AND x.report_artifact_id=p_artifact)\n"
        "  OR EXISTS(SELECT FROM photo.session_analyses x WHERE x.tenant_id=p_tenant AND x.plan_artifact_id=p_artifact)\n"
        "  OR EXISTS(SELECT FROM photo.person_observations x WHERE x.tenant_id=p_tenant AND x.evidence_artifact_id=p_artifact)",
    )
    purge = (SCAFFOLDS / "00196_purge.sql").read_text()
    purge = replace_once(
        purge,
        "  'v2_document_approvals','v2_document_refs'",
        "  'workflow_consent_links','consent_events','person_observations','scene_members',"
        "'scene_groups','session_analyses','consent_grants','project_persons','shoot_sessions',\n"
        "  'v2_document_approvals','v2_document_refs'",
    )
    return ("-- Generated by scripts/build-v22-gc-purge.py; do not edit.\n"
            "-- V22 references and tenant metadata are covered only after object cleanup.\n"
            + gc.strip() + "\n\n" + purge.strip() + "\n")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = render()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != expected:
            raise SystemExit("V22 GC/purge extension is stale")
    else:
        OUTPUT.write_text(expected)


if __name__ == "__main__":
    main()
