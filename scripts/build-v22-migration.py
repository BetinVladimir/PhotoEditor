#!/usr/bin/env python3
"""Assemble the forward-only V22 SQL slice in verified dependency order."""

from pathlib import Path
import argparse


ROOT = Path(__file__).resolve().parents[1]
SCAFFOLDS = ROOT / "backend/db/v2-scaffolds"
PARTS = (
    "00197_schema.sql",
    "00197_operations.sql",
    "00197_scope_guards.sql",
    "00197_session_mutations.sql",
    "00197_person_mutations.sql",
    "00197_adoption_consent_gate.sql",
    "00197_session_plan_inputs.sql",
    "00197_session_plan_lease.sql",
    "00197_session_plan_documents.sql",
    "00197_session_plan_stage.sql",
    "00197_session_plan_close.sql",
    "00197_session_plan_frozen.sql",
    "00197_consent_mutations.sql",
    "00197_observation_mutations.sql",
    "00197_analysis_preflight.sql",
    "00197_analysis_snapshot.sql",
    "00197_analysis_begin.sql",
    "00197_analysis_recovery.sql",
    "00197_analysis_replay.sql",
    "00197_analysis_documents.sql",
    "00197_analysis_stage.sql",
    "00197_analysis_image_source.sql",
    "00197_analysis_consent_source.sql",
    "00197_analysis_consent_pin.sql",
    "00197_gc_purge.sql",
)
OUTPUT = SCAFFOLDS / "00197_assembled.sql"
LIVE_OUTPUT = ROOT / "backend/db/migrations/00198_v22_session_foundation.sql"


def render() -> str:
    sections = ["-- Generated by scripts/build-v22-migration.py; do not edit.\n-- +goose Up\n"]
    for filename in PARTS:
        body = (SCAFFOLDS / filename).read_text().strip()
        if "-- +goose Up" in body or "-- +goose Down" in body:
            raise ValueError(f"Nested migration boundary in {filename}")
        sections.append(f"\n-- Source: {filename}\n{body}\n")
    sections.append(
        "\n-- +goose Down\n-- +goose StatementBegin\n"
        "DO $$ BEGIN RAISE EXCEPTION 'Forward-only migration'; END $$;\n"
        "-- +goose StatementEnd\n"
    )
    return "".join(sections)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = render()
    if args.check:
        if (not OUTPUT.exists() or OUTPUT.read_text() != expected or
                not LIVE_OUTPUT.exists() or LIVE_OUTPUT.read_text() != expected):
            raise SystemExit("V22 assembly is stale; rerun scripts/build-v22-migration.py")
    else:
        OUTPUT.write_text(expected)
        LIVE_OUTPUT.write_text(expected)


if __name__ == "__main__":
    main()
