#!/usr/bin/env python3
"""Assemble the forward-only V21 database migration in dependency order."""

from pathlib import Path
import argparse


ROOT = Path(__file__).resolve().parents[1]
SCAFFOLDS = ROOT / "backend/db/v2-scaffolds"
PARTS = (
    "00196_run_kind.sql",
    "00196_run_config_guard.sql",
    "00196_schema.sql",
    "00196_input_documents.sql",
    "00196_draft_indexes.sql",
    "00196_guards.sql",
    "00196_project_guards.sql",
    "00196_artifact_guards.sql",
    "00196_review_guards.sql",
    "00196_authority.sql",
    "00196_draft_publication.sql",
    "00196_draft_scope.sql",
    "00196_draft_refs.sql",
    "00196_draft_mutations.sql",
    "00196_draft_approval.sql",
    "00196_capabilities.sql",
    "00196_gc_refs.sql",
    "00196_gc_integration.sql",
    "00196_input_closure_gate.sql",
    "00196_task_input_registration.sql",
    "00196_draft_shell.sql",
    "00196_pending_replay_guard.sql",
    "00196_admission_idempotency.sql",
    "00196_graph_seal.sql",
    "00196_draft_expiry.sql",
    "00196_gateway_input.sql",
    "00196_output_protocol.sql",
    "00196_worker_renderer_gate.sql",
    "00196_result_root.sql",
    "00196_adoption.sql",
    "00196_adoption_reads.sql",
    "00196_finalize.sql",
    "00196_purge.sql",
)
OUTPUT = SCAFFOLDS / "00196_assembled.sql"
LIVE_OUTPUT = ROOT / "backend/db/migrations/00197_v21_foundation.sql"


def render() -> str:
    sections = ["-- Generated by scripts/build-v2-migration.py; do not edit.\n-- +goose Up\n"]
    for filename in PARTS:
        body = (SCAFFOLDS / filename).read_text().strip()
        if "-- +goose Up" in body or "-- +goose Down" in body:
            raise ValueError(f"Nested migration boundary in {filename}")
        sections.append(f"\n-- Source: {filename}\n{body}\n")
    sections.append(
        "\n-- +goose Down\n-- +goose StatementBegin\n"
        "DO $$ BEGIN RAISE EXCEPTION 'Forward-only migration'; END $$;\n"
        "-- +goose StatementEnd\n"
    )
    return "".join(sections)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = render()
    if args.check:
        if (not OUTPUT.exists() or OUTPUT.read_text() != expected or
                not LIVE_OUTPUT.exists() or LIVE_OUTPUT.read_text() != expected):
            raise SystemExit("V21 assembly is stale; rerun scripts/build-v2-migration.py")
    else:
        OUTPUT.write_text(expected)
        LIVE_OUTPUT.write_text(expected)


if __name__ == "__main__":
    main()
