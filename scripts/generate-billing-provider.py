#!/usr/bin/env python3
"""Generate billing provider schema and function migrations from contracts/provider-*.json."""
import argparse
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
SCHEMA = '02662_billing_provider_schema.sql'
FUNCTIONS = '02663_billing_provider_functions.sql'
IDENT = re.compile(r'^[a-z][a-z0-9_]{0,62}$')
TYPES = {'uuid','text','boolean','integer','bigint','bytea','timestamptz','char(2)','jsonb'}

def ident(value):
    if not IDENT.fullmatch(value): raise ValueError('Invalid billing identifier: '+repr(value))
    return value

def render(root=ROOT):
    source = root / 'docs/billing/contracts'
    catalog = json.loads((source / 'provider-tables.json').read_text())
    functions = json.loads((source / 'provider-functions.json').read_text())
    if catalog['schema_version'] != 1 or functions['schema_version'] != 1:
        raise ValueError('Unsupported provider schema version')
    if not catalog['tables'] and not functions['functions']:
        return {}
    down = "\n-- +goose Down\n-- +goose StatementBegin\nDO $$ BEGIN RAISE EXCEPTION 'Forward-only billing provider migration'; END $$;\n-- +goose StatementEnd\n"
    result = {}
    if catalog['tables']:
        header = '-- Generated by scripts/generate-billing-provider.py; DO NOT EDIT.\n-- +goose Up\n'
        ddl = [header]
        seen = set()
        for table in catalog['tables']:
            name = ident(table['name'])
            if name in seen: raise ValueError('Duplicate table: ' + name)
            seen.add(name)
            columns = []; keys = set()
            for column in table['columns']:
                key = ident(column['name'])
                if key in keys: raise ValueError('Duplicate column: ' + key)
                if column['type'] not in TYPES: raise ValueError('Unsupported type: ' + column['type'])
                keys.add(key)
                col = key + ' ' + column['type']
                if not column.get('nullable', True): col += ' NOT NULL'
                if 'default' in column: col += ' DEFAULT ' + column['default']
                columns.append(col)
            if not set(table['primary_key']) <= keys: raise ValueError('Invalid primary key for ' + name)
            columns += ['PRIMARY KEY (' + ','.join(map(ident, table['primary_key'])) + ')'] + table['constraints']
            ddl.append('CREATE TABLE photo.' + name + ' (\n ' + ',\n '.join(columns) + '\n);')
            ddl += [i + ';' for i in table['indexes']]
            expected = ['SELECT', 'INSERT'] + ([] if table.get('append_only') else ['UPDATE'])
            if table['acl'] != {'photo_fn_owner': expected} or table['rls'] != 'force_trusted_functions':
                raise ValueError('Unexpected provider ACL for ' + name)
            ddl += [
                'REVOKE ALL ON photo.' + name + ' FROM PUBLIC;',
                'ALTER TABLE photo.' + name + ' ENABLE ROW LEVEL SECURITY;',
                'ALTER TABLE photo.' + name + ' FORCE ROW LEVEL SECURITY;',
                'CREATE POLICY billing_provider ON photo.' + name + ' TO photo_fn_owner USING (true) WITH CHECK (true);',
                'GRANT ' + ','.join(expected) + ' ON photo.' + name + ' TO photo_fn_owner;',
            ]
        result[SCHEMA] = '\n\n'.join(ddl) + down

    if functions['functions']:
        header = '-- Generated by scripts/generate-billing-provider.py; DO NOT EDIT.\n-- +goose Up\n'
        body = (source / 'provider-functions.sql').read_text()
        chunks = re.split(r'(?=CREATE FUNCTION photo\.)', body)
        code = [header, chunks[0]]
        parsed = []
        for chunk in chunks[1:]:
            match = re.match(r'CREATE FUNCTION photo\.([a-z_]+)\(([^)]*)\)', chunk)
            if not match: raise ValueError('Invalid function declaration')
            name, args = match.groups()
            types = ','.join(arg.strip().split()[1] for arg in args.split(',') if arg.strip())
            signature = name + '(' + types + ')'
            entry = next((f for f in functions['functions'] if f['signature'] == signature), None)
            if entry is None: raise ValueError('Provider signature not in JSON: ' + signature)
            if entry['owner'] != 'photo_fn_owner': raise ValueError('Unexpected owner for ' + signature)
            if 'SECURITY DEFINER SET search_path=pg_catalog,photo' not in chunk:
                raise ValueError('Unsafe provider function: ' + signature)
            grants = entry.get('execute_roles', [])
            for role in grants:
                if role not in ('photo_worker',):
                    raise ValueError('Unapproved execute_role for provider function ' + signature + ': ' + role)
            code += [
                '-- +goose StatementBegin\n' + chunk.strip() + '\n-- +goose StatementEnd',
                'ALTER FUNCTION photo.' + signature + ' OWNER TO photo_fn_owner;',
                'REVOKE ALL ON FUNCTION photo.' + signature + ' FROM PUBLIC;',
            ]
            for role in grants:
                code.append('GRANT EXECUTE ON FUNCTION photo.' + signature + ' TO ' + role + ';')
            parsed.append(signature)
        if set(parsed) != {f['signature'] for f in functions['functions']} or len(parsed) != len(functions['functions']):
            raise ValueError('Provider function set mismatch')
        result[FUNCTIONS] = '\n\n'.join(code) + down

    return result

def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--check', action='store_true')
    args = p.parse_args()
    rendered = render()
    if not rendered:
        if args.check:
            for name in [SCHEMA, FUNCTIONS]:
                if (ROOT / 'backend/db/migrations' / name).exists():
                    raise SystemExit('Provider migration exists but contracts are empty: ' + name)
        return
    for name, content in rendered.items():
        path = ROOT / 'backend/db/migrations' / name
        if args.check:
            if not path.exists() or path.read_text() != content:
                raise SystemExit('Provider generated migration drift: ' + name)
        else:
            path.write_text(content)

if __name__ == '__main__':
    main()
