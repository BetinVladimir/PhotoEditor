#!/usr/bin/env python3
"""Generate the additive Standalone operation accounting boundary; historical sources stay pinned."""
import argparse,re
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
def render():
    body=(ROOT/'docs/billing/contracts/selected-workflow.sql').read_text()
    body=re.sub(r'(CREATE (?:OR REPLACE )?FUNCTION photo\.[\s\S]*?\n(?:END )?\$\$;)',r'-- +goose StatementBegin\n\1\n-- +goose StatementEnd',body)
    body=re.sub(r'(DO \$\$[\s\S]*?END \$\$;)',r'-- +goose StatementBegin\n\1\n-- +goose StatementEnd',body)
    return '-- Generated by scripts/generate-billing-selected.py; DO NOT EDIT.\n'+body+"\n-- +goose Down\n-- +goose StatementBegin\nDO $$ BEGIN RAISE EXCEPTION 'Forward-only operation billing migration'; END $$;\n-- +goose StatementEnd\n"
if __name__=='__main__':
    p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');args=p.parse_args()
    path=ROOT/'backend/db/migrations/02609_billing_selected_workflow.sql'
    if args.check:
        if path.read_text()!=render():raise SystemExit('Operation billing migration drift')
    else:path.write_text(render())
