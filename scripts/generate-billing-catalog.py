#!/usr/bin/env python3
"""Generate only the additive billing scaffold; historical baseline is never rewritten."""
import argparse
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
SCHEMA_FILE = '02598_billing_catalog_scaffold.sql'
SEED_FILE = '02599_billing_catalog_seed.sql'
IDENT = re.compile(r'^[a-z][a-z0-9_]{0,62}$')
TYPES = {'uuid', 'text', 'boolean', 'integer', 'bigint', 'bytea', 'timestamptz'}

def identifier(value):
    if not isinstance(value, str) or not IDENT.fullmatch(value):
        raise ValueError(f'Invalid SQL identifier: {value!r}')
    return value

def literal(value):
    if value is None:
        return 'NULL'
    if type(value) is bool:
        return 'true' if value else 'false'
    if type(value) is int:
        if not -(2**63) <= value < 2**63:
            raise ValueError('Integer outside PostgreSQL bigint range')
        return str(value)
    if isinstance(value, str):
        if '\x00' in value:
            raise ValueError('NUL in SQL literal')
        # Explicit escape syntax is independent of standard_conforming_strings.
        return "E'" + value.replace('\\', '\\\\').replace("'", "''") + "'"
    raise ValueError('Only typed scalar seed values are supported')

def load_contracts(root=ROOT):
    directory = root / 'docs/billing/contracts'
    catalog = json.loads((directory / 'tables.json').read_text())
    seed = json.loads((directory / 'seed.json').read_text())
    functions = json.loads((directory / 'functions.json').read_text())
    if any(c['schema_version'] != 1 for c in (catalog, seed, functions)):
        raise ValueError('Unsupported billing contract version')
    if functions['functions']:
        raise ValueError('Scaffold generator does not implement SQL functions')
    names = set()
    for table in catalog['tables']:
        name = identifier(table['name'])
        if name in names:
            raise ValueError('Duplicate table')
        names.add(name)
        columns = set()
        for column in table['columns']:
            col = identifier(column['name'])
            if col in columns or column['type'] not in TYPES or type(column['nullable']) is not bool:
                raise ValueError('Invalid or duplicate column')
            columns.add(col)
        if not set(table['primary_key']) <= columns:
            raise ValueError('Unknown primary key column')
        if table['acl'] != {'photo_fn_owner': ['SELECT']} or table['rls'] != 'force_no_runtime_policy':
            raise ValueError('Scaffold must deny runtime access')
        for row in seed['rows'].get(name, []):
            if not set(row) <= columns or 'id' not in row:
                raise ValueError('Unknown seed column or missing identity')
            for column in table['columns']:
                if not column['nullable'] and 'default' not in column and row.get(column['name']) is None:
                    raise ValueError('Missing required seed value')
    if set(seed['rows']) != names:
        raise ValueError('Seed table set differs from schema')
    return catalog, seed

def render(root=ROOT):
    catalog, seed = load_contracts(root)
    header = '-- Code generated by scripts/generate-billing-catalog.py; DO NOT EDIT.\n-- +goose Up\n'
    ddl = [header, '-- Closed scaffold: a later migration must qualify publication, provisioning and runtime access.']
    for table in catalog['tables']:
        name = identifier(table['name'])
        columns = []
        for col in table['columns']:
            text = identifier(col['name']) + ' ' + col['type']
            if not col['nullable']:
                text += ' NOT NULL'
            if 'default' in col:
                text += ' DEFAULT ' + col['default']
            columns.append(text)
        columns += ['PRIMARY KEY (' + ','.join(map(identifier, table['primary_key'])) + ')']
        columns += table['constraints'] + ['CHECK (' + check + ')' for check in table['checks']]
        ddl.append('CREATE TABLE photo.' + name + ' (\n  ' + ',\n  '.join(columns) + '\n);')
        ddl += [index + ';' for index in table['indexes']]
        ddl += ['REVOKE ALL ON photo.' + name + ' FROM PUBLIC;',
                'ALTER TABLE photo.' + name + ' ENABLE ROW LEVEL SECURITY;',
                'ALTER TABLE photo.' + name + ' FORCE ROW LEVEL SECURITY;',
                'GRANT SELECT ON photo.' + name + ' TO photo_fn_owner;']
        # No policies: even fn_owner cannot read until an authorized function is introduced.
    inserts = [header, '-- Immutable initial sandbox seed. Replaying accepts only exactly matching rows.']
    for table in catalog['tables']:
        name = table['name']
        for row in seed['rows'][name]:
            keys = list(row)
            values = [literal(row[key]) for key in keys]
            inserts.append('INSERT INTO photo.' + name + '(' + ','.join(keys) + ') VALUES (' + ','.join(values) + ') ON CONFLICT(id) DO NOTHING;')
            compare = ' AND '.join(key + ' IS NOT DISTINCT FROM ' + literal(row[key]) for key in keys)
            inserts.append('-- +goose StatementBegin\nDO $seed$ BEGIN\n IF NOT EXISTS (SELECT 1 FROM photo.' + name + ' WHERE ' + compare + ") THEN\n  RAISE EXCEPTION 'Billing seed collision: " + name + '/' + row['id'] + "';\n END IF;\nEND $seed$;\n-- +goose StatementEnd")
    down = "\n-- +goose Down\n-- +goose StatementBegin\nDO $$ BEGIN RAISE EXCEPTION 'Forward-only billing migration'; END $$;\n-- +goose StatementEnd\n"
    return {SCHEMA_FILE: '\n\n'.join(ddl) + down, SEED_FILE: '\n\n'.join(inserts) + down}

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for name, contents in render().items():
        path = ROOT / 'backend/db/migrations' / name
        if args.check:
            if not path.exists() or path.read_text() != contents:
                raise SystemExit(f'Billing generated migration drift: {name}')
        else:
            path.write_text(contents)

if __name__ == '__main__':
    main()
