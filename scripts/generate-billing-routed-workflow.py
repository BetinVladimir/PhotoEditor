#!/usr/bin/env python3
"""Generate additive routed Apply billing; historical migrations stay pinned."""
import argparse,re
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
def render():
    body=(ROOT/'docs/billing/contracts/routed-workflow.sql').read_text()
    body=re.sub(r'(CREATE (?:OR REPLACE )?FUNCTION photo\.[\s\S]*?\nEND \$\$;)',r'-- +goose StatementBegin\n\1\n-- +goose StatementEnd',body)
    return '-- Generated by scripts/generate-billing-routed-workflow.py; DO NOT EDIT.\n'+body+"\n-- +goose Down\n-- +goose StatementBegin\nDO $$ BEGIN RAISE EXCEPTION 'Forward-only billing routed workflow migration'; END $$;\n-- +goose StatementEnd\n"
if __name__=='__main__':
    p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');args=p.parse_args()
    path=ROOT/'backend/db/migrations/02604_billing_routed_apply.sql'
    if args.check:
        if path.read_text()!=render():raise SystemExit('Routed workflow migration drift')
    else:path.write_text(render())
