#!/usr/bin/env python3
"""Render a guarded forward-only correction of the legal acceptance function."""
import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MIGRATION = '02671_billing_legal_acceptance_hardening.sql'


def render(root=ROOT):
    base = root / 'docs/billing/contracts'
    contract = json.loads((base / 'legal-hardening-functions.json').read_text())
    entry, = contract['functions']
    signature = 'account_accept_legal(uuid,uuid,uuid,jsonb,jsonb,text)'
    if contract['schema_version'] != 1 or entry['signature'] != signature or entry['owner'] != 'photo_fn_owner' or entry['execute_roles'] != ['photo_auth']:
        raise ValueError('Unsafe legal correction contract')
    source = (base / 'legal-hardening-functions.sql').read_text().strip()
    if not source.startswith('CREATE OR REPLACE FUNCTION photo.account_accept_legal(') or 'SECURITY DEFINER SET search_path=pg_catalog,photo' not in source:
        raise ValueError('Unsafe legal correction source')
    body = source.split('AS $$', 1)[1].rsplit('$$;', 1)[0]
    if hashlib.sha256(body.encode()).hexdigest() != entry['postimage_sha256']:
        raise ValueError('Legal correction body does not match manifest')
    for field in ('preimage_sha256', 'postimage_sha256'):
        if len(entry[field]) != 64 or any(c not in '0123456789abcdef' for c in entry[field]):
            raise ValueError('Invalid legal correction digest')
    sql = f"""-- Generated by scripts/generate-billing-legal-hardening.py; DO NOT EDIT.
-- +goose Up
-- +goose StatementBegin
CREATE TEMP TABLE pg_temp.legal_acceptance_preimage(target oid,catalog jsonb) ON COMMIT DROP;
DO $guard$
DECLARE target oid:=to_regprocedure('photo.{signature}'); p pg_proc%ROWTYPE;
BEGIN
 IF target IS NULL THEN RAISE EXCEPTION 'LEGAL_ACCEPTANCE_PREIMAGE_MISSING';END IF;
 SELECT * INTO p FROM pg_proc WHERE oid=target;
 IF encode(sha256(convert_to(p.prosrc,'UTF8')),'hex')<>'{entry['preimage_sha256']}'
 OR p.proowner<>'photo_fn_owner'::regrole OR NOT p.prosecdef OR p.prokind<>'f' OR NOT p.proretset
 OR p.prorettype<>'record'::regtype OR p.prolang<>(SELECT oid FROM pg_language WHERE lanname='plpgsql')
 OR p.proconfig IS NULL OR array_length(p.proconfig,1)<>1
 OR replace(p.proconfig[1],' ','')<>'search_path=pg_catalog,photo'
 THEN RAISE EXCEPTION 'LEGAL_ACCEPTANCE_PREIMAGE_CHANGED';END IF;
 IF EXISTS(SELECT FROM aclexplode(coalesce(p.proacl,acldefault('f',p.proowner))) a
  WHERE a.grantee NOT IN(p.proowner,'photo_auth'::regrole) OR a.grantor<>p.proowner
  OR a.privilege_type<>'EXECUTE' OR a.is_grantable)
 OR NOT EXISTS(SELECT FROM aclexplode(coalesce(p.proacl,acldefault('f',p.proowner))) a
  WHERE a.grantee='photo_auth'::regrole AND a.privilege_type='EXECUTE')
 THEN RAISE EXCEPTION 'LEGAL_ACCEPTANCE_ACL_CHANGED';END IF;
 INSERT INTO pg_temp.legal_acceptance_preimage SELECT target,to_jsonb(p)-'prosrc';
END $guard$;
-- +goose StatementEnd
-- +goose StatementBegin
{source}
-- +goose StatementEnd
-- +goose StatementBegin
DO $post$
DECLARE prior record; actual pg_proc%ROWTYPE;
BEGIN
 SELECT * INTO prior FROM pg_temp.legal_acceptance_preimage;
 SELECT * INTO actual FROM pg_proc WHERE oid=prior.target;
 IF actual.oid IS NULL OR to_jsonb(actual)-'prosrc' IS DISTINCT FROM prior.catalog
 OR encode(sha256(convert_to(actual.prosrc,'UTF8')),'hex')<>'{entry['postimage_sha256']}'
 OR to_regprocedure('photo.{signature}') IS DISTINCT FROM prior.target
 THEN RAISE EXCEPTION 'LEGAL_ACCEPTANCE_POSTCONDITION_FAILED';END IF;
END $post$;
-- +goose StatementEnd
-- +goose Down
-- +goose StatementBegin
DO $$ BEGIN RAISE EXCEPTION 'Forward-only legal acceptance correction';END $$;
-- +goose StatementEnd
"""
    return {MIGRATION: sql}


def main():
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--check',action='store_true');args=parser.parse_args()
    for name,body in render().items():
        path=ROOT/'backend/db/migrations'/name
        if args.check:
            if not path.exists() or path.read_text()!=body: raise SystemExit('Legal correction migration drift: '+name)
        elif path.exists() and path.read_text()!=body: raise SystemExit('Refusing to overwrite existing migration: '+name)
        else: path.write_text(body)

if __name__=='__main__':main()
