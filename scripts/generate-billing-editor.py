#!/usr/bin/env python3
"""Generate the additive Editor effects accounting boundary; historical sources stay pinned."""
import argparse,re
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
def automatic_blocks(body):
    body=re.sub(r'(CREATE (?:OR REPLACE )?FUNCTION photo\.[\s\S]*?\n(?:END )?\$\$;)',r'-- +goose StatementBegin\n\1\n-- +goose StatementEnd',body)
    return re.sub(r'(DO \$\$[\s\S]*?END \$\$;)',r'-- +goose StatementBegin\n\1\n-- +goose StatementEnd',body)

def statement_blocks(body):
    # Explicit top-level Goose blocks are opaque. Do not regex into dynamic SQL.
    result=[];pending=[];manual=[];inside=False
    for line in body.splitlines(keepends=True):
        marker=line.rstrip('\r\n')
        if marker=='-- +goose StatementBegin':
            if inside:raise ValueError('Nested manual Goose block')
            result.append(automatic_blocks(''.join(pending)));pending=[];inside=True;manual=[line]
        elif marker=='-- +goose StatementEnd':
            if not inside:raise ValueError('Unbalanced manual Goose end')
            manual.append(line);result.append(''.join(manual));manual=[];inside=False
        else:
            if '-- +goose StatementBegin' in line or '-- +goose StatementEnd' in line:raise ValueError('Malformed manual Goose marker')
            (manual if inside else pending).append(line)
    if inside:raise ValueError('Unclosed manual Goose block')
    result.append(automatic_blocks(''.join(pending)))
    return ''.join(result)

def render(body=None):
    if body is None:body=(ROOT/'docs/billing/contracts/editor-workflow.sql').read_text()
    body=statement_blocks(body)
    return '-- Generated by scripts/generate-billing-editor.py; DO NOT EDIT.\n'+body+"\n-- +goose Down\n-- +goose StatementBegin\nDO $$ BEGIN RAISE EXCEPTION 'Forward-only editor billing migration'; END $$;\n-- +goose StatementEnd\n"
if __name__=='__main__':
    p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');args=p.parse_args()
    path=ROOT/'backend/db/migrations/02606_billing_editor_workflow.sql'
    if args.check:
        if path.read_text()!=render():raise SystemExit('Editor billing migration drift')
    else:path.write_text(render())
