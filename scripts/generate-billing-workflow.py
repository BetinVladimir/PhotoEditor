#!/usr/bin/env python3
"""Generate the additive standard Apply billing boundary, preserving the installed adopters."""
import argparse
import json
from pathlib import Path
import re
ROOT=Path(__file__).resolve().parents[1]

def render(root=ROOT):
    source=root/'docs/billing/contracts'
    manifest=json.loads((source/'workflow-functions.json').read_text())
    result={}
    for stem,name in [('schema','02602_billing_apply_bindings.sql'),('functions','02603_billing_apply_workflow.sql')]:
        body=(source/f'workflow-{stem}.sql').read_text()
        if body.count('-- +goose Up')!=1 or '-- +goose Down' in body:raise ValueError('Invalid workflow migration source')
        if stem=='functions':
            definitions=re.findall(r'CREATE FUNCTION photo\.([a-z_]+)\(([^)]*)\)',body)
            signatures=[n+'('+','.join(a.strip().split()[1] for a in args.split(',') if a.strip())+')' for n,args in definitions]
            if len(signatures)!=len(set(signatures)) or set(signatures)!={f['signature'] for f in manifest['functions']}:raise ValueError('Workflow function contract drift')
            for entry in manifest['functions']:
                signature=entry['signature'];roles=entry['execute_roles']
                if any(r not in ('photo_api','photo_scheduler') for r in roles):raise ValueError('Unreviewed workflow grant')
                body+='\nALTER FUNCTION photo.'+signature+' OWNER TO photo_fn_owner;\nREVOKE ALL ON FUNCTION photo.'+signature+' FROM PUBLIC;\n'
                if roles:body+='GRANT EXECUTE ON FUNCTION photo.'+signature+' TO '+','.join(roles)+';\n'
            # Goose needs each complete CREATE FUNCTION, including semicolons inside its body.
            body=re.sub(r'(CREATE FUNCTION photo\.[\s\S]*?\n(?:END \$\$;))',r'-- +goose StatementBegin\n\1\n-- +goose StatementEnd',body)
        result[name]='-- Generated by scripts/generate-billing-workflow.py; DO NOT EDIT.\n'+body+"\n-- +goose Down\n-- +goose StatementBegin\nDO $$ BEGIN RAISE EXCEPTION 'Forward-only billing workflow migration'; END $$;\n-- +goose StatementEnd\n"
    return result

def main():
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--check',action='store_true');args=p.parse_args()
    for name,text in render().items():
        path=ROOT/'backend/db/migrations'/name
        if args.check:
            if not path.exists() or path.read_text()!=text:raise SystemExit('Workflow migration drift: '+name)
        else:path.write_text(text)
if __name__=='__main__':main()
