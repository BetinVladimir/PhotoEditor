#!/usr/bin/env python3
"""Render additive, auth-only privacy worker migrations."""
import argparse
import hashlib
import json
from pathlib import Path
import re

ROOT=Path(__file__).resolve().parents[1]
SCHEMA='02676_billing_deletion_preflight_schema.sql'
FUNCTIONS='02677_billing_deletion_preflight_functions.sql'


def render(root=ROOT):
    base=root/'docs/billing/contracts'
    manifest=json.loads((base/'deletion-preflight-functions.json').read_text())
    schema=(base/'deletion-preflight-schema.sql').read_text()
    source=(base/'deletion-preflight-functions.sql').read_text()
    if manifest['schema_version']!=1 or hashlib.sha256(schema.encode()).hexdigest()!=manifest['schema_sha256']:
        raise ValueError('Privacy schema manifest drift')
    if not schema.startswith('CREATE TABLE photo.profile_deletion_preflights (') or 'GRANT DELETE' in schema or 'DROP ' in schema:
        raise ValueError('Unsafe privacy schema')
    header='-- Generated by scripts/generate-billing-deletion-preflight.py; DO NOT EDIT.\n-- +goose Up\n'
    refusal="\n-- +goose Down\n-- +goose StatementBegin\nDO $$ BEGIN RAISE EXCEPTION 'Forward-only privacy worker migration';END $$;\n-- +goose StatementEnd\n"
    outputs=[];seen=[]
    for chunk in re.split(r'(?=CREATE FUNCTION photo\.)',source)[1:]:
        match=re.match(r'CREATE FUNCTION photo\.([a-z_]+)\(([^)]*)\)',chunk)
        if not match: raise ValueError('Invalid privacy declaration')
        name,args=match.groups()
        signature=name+'('+','.join(a.strip().split()[1] for a in args.split(','))+')'
        entry=next((f for f in manifest['functions'] if f['signature']==signature),None)
        if entry is None or entry['owner']!='photo_fn_owner' or entry['execute_roles']!=['photo_auth']:
            raise ValueError('Unsafe privacy function ACL')
        if 'SECURITY DEFINER SET search_path=pg_catalog,photo' not in chunk or len(chunk.splitlines())>80:
            raise ValueError('Unsafe privacy function configuration')
        outputs.extend(['-- +goose StatementBegin\n'+chunk.strip()+'\n-- +goose StatementEnd',
            'ALTER FUNCTION photo.'+signature+' OWNER TO photo_fn_owner;',
            'REVOKE ALL ON FUNCTION photo.'+signature+' FROM PUBLIC;',
            'GRANT EXECUTE ON FUNCTION photo.'+signature+' TO photo_auth;'])
        seen.append(signature)
    if len(seen)!=len(set(seen)) or set(seen)!={f['signature'] for f in manifest['functions']}:
        raise ValueError('Privacy function inventory mismatch')
    return {SCHEMA:header+schema+refusal,FUNCTIONS:header+'\n\n'.join(outputs)+refusal}


def main():
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--check',action='store_true');args=parser.parse_args()
    for name,body in render().items():
        path=ROOT/'backend/db/migrations'/name
        if args.check:
            if not path.exists() or path.read_text()!=body: raise SystemExit('Privacy migration drift: '+name)
        elif path.exists() and path.read_text()!=body: raise SystemExit('Refusing to overwrite existing migration: '+name)
        else:path.write_text(body)

if __name__=='__main__':main()
