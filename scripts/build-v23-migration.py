#!/usr/bin/env python3
"""Assemble V23 learning metadata foundation with GC and tenant purge hooks."""
from __future__ import annotations

import argparse
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
SCAFFOLDS = ROOT / 'backend/db/v2-scaffolds'
OUTPUT = ROOT / 'backend/db/migrations/00204_v23_learning_foundation.sql'

IMMUTABLE = (
    'correction_events', 'learning_versions', 'learning_example_links',
    'model_use_links', 'profile_activations', 'learning_safety_reviews',
)


def replace_once(source: str, old: str, new: str) -> str:
    if source.count(old) != 1:
        raise ValueError(f'Missing or repeated V23 migration anchor: {old[:80]}')
    return source.replace(old, new, 1)


def render() -> str:
    schema = (SCAFFOLDS / '00198_schema.sql').read_text().strip()
    if '-- +goose Up' in schema or '-- +goose Down' in schema:
        raise ValueError('V23 schema scaffold contains migration boundary')
    gc = (SCAFFOLDS / '00197_gc_purge.sql').read_text()
    gc = replace_once(
        gc,
        "  OR EXISTS(SELECT FROM photo.v2_draft_uploads x WHERE x.tenant_id=p_tenant AND x.artifact_id=p_artifact AND x.state='ready')",
        "  OR EXISTS(SELECT FROM photo.learning_versions x WHERE x.tenant_id=p_tenant AND p_artifact IN(x.training_artifact_id,x.model_artifact_id,x.evaluation_artifact_id))\n"
        "  OR EXISTS(SELECT FROM photo.consent_cleanup x WHERE x.tenant_id=p_tenant AND x.artifact_id=p_artifact)\n"
        "  OR EXISTS(SELECT FROM photo.v2_draft_uploads x WHERE x.tenant_id=p_tenant AND x.artifact_id=p_artifact AND x.state='ready')",
    )
    gc = replace_once(
        gc,
        "  'workflow_consent_links','consent_events'",
        "  'learning_safety_reviews','model_use_links','learning_example_links','profile_activations','version_eligibility','consent_cleanup','learning_versions','correction_events','learning_profiles','v22_analysis_decisions',\n"
        "  'workflow_consent_links','consent_events'",
    )
    gc = gc.replace('-- Generated by scripts/build-v22-gc-purge.py; do not edit.\n'
                    '-- V22 references and tenant metadata are covered only after object cleanup.\n',
                    '-- V23 artifact references and metadata purge extension.\n', 1)
    immutable = '\n'.join(
        f'CREATE TRIGGER {table}_immutable BEFORE UPDATE ON photo.{table} '
        'FOR EACH ROW EXECUTE FUNCTION photo.guard_v2_immutable();'
        for table in IMMUTABLE)
    return ('-- Generated by scripts/build-v23-migration.py; do not edit.\n'
            '-- V23 metadata foundation only: no API writer or operation registry is enabled.\n'
            '-- +goose Up\n\n' + schema + '\n\n' + immutable + '\n\n'
            + gc.strip() + '\n\n-- +goose Down\n-- +goose StatementBegin\n'
            "DO $$ BEGIN RAISE EXCEPTION 'Forward-only migration'; END $$;\n"
            '-- +goose StatementEnd\n')


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    expected = render()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != expected:
            raise SystemExit('V23 migration is stale')
    else:
        OUTPUT.write_text(expected)


if __name__ == '__main__':
    main()
