#!/usr/bin/env python3
"""Extract the nine V23 learning tables from the normative schema registry."""
from __future__ import annotations

import argparse
import json
import re
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
REFERENCE = ROOT / 'docs/implementation-v2/contracts/schema-reference.sql'
REGISTRY = ROOT / 'docs/implementation-v2/contracts/database.json'
OUTPUT = ROOT / 'backend/db/v2-scaffolds/00198_schema.sql'


def render() -> str:
    registry = json.loads(REGISTRY.read_text())
    names = {entry['name'] for entry in registry['tables']
             if entry['migration'] == 198}
    if len(names) != 9:
        raise ValueError('Unexpected V23 table registry')
    raw = REFERENCE.read_text()
    statements = [piece.strip() + ';' for piece in raw.split(';') if piece.strip()]
    selected = []
    for statement in statements:
        statement = re.sub(r'^--[^\n]*\n(?:\n)*', '', statement).strip()
        table = re.match(r'(?:CREATE TABLE|ALTER TABLE|CREATE INDEX ON|'
                         r'CREATE UNIQUE INDEX ON|CREATE POLICY \w+ ON|'
                         r'REVOKE ALL ON|GRANT [A-Z, ]+ ON) photo\.(\w+)\b',
                         statement)
        if table and table.group(1) in names:
            selected.append(statement)
    created = {re.match(r'CREATE TABLE photo\.(\w+)', value).group(1)
               for value in selected if value.startswith('CREATE TABLE')}
    if created != names:
        raise ValueError('Missing V23 table declarations')
    tables = [value for value in selected if value.startswith('CREATE TABLE')]
    others = [value for value in selected if not value.startswith('CREATE TABLE')]
    return ('-- Generated by scripts/build-v23-schema.py; V23 table scaffold.\n'
            + '\n\n'.join([*tables, *others]) + '\n')


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    expected = render()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != expected:
            raise SystemExit('V23 schema scaffold is stale')
    else:
        OUTPUT.write_text(expected)


if __name__ == '__main__':
    main()
