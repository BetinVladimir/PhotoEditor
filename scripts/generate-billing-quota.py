#!/usr/bin/env python3
"""Generate the closed, shadow-only quota kernel without rewriting earlier migrations."""
import argparse
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
SCHEMA = '02600_billing_quota_accounting.sql'
FUNCTIONS = '02601_billing_quota_functions.sql'
IDENT = re.compile(r'^[a-z][a-z0-9_]{0,62}$')
TYPES = {'uuid','text','boolean','integer','bigint','bytea','timestamptz'}

def ident(value):
    if not IDENT.fullmatch(value): raise ValueError('Invalid billing identifier')
    return value

def render(root=ROOT):
    source=root/'docs/billing/contracts'
    catalog=json.loads((source/'quota-tables.json').read_text())
    functions=json.loads((source/'quota-functions.json').read_text())
    if catalog['schema_version']!=1 or functions['schema_version']!=1: raise ValueError('Unsupported quota schema version')
    header='-- Generated by scripts/generate-billing-quota.py; DO NOT EDIT.\n-- +goose Up\n'
    ddl=[header]
    seen=set()
    for table in catalog['tables']:
        name=ident(table['name'])
        if name in seen: raise ValueError('Duplicate table')
        seen.add(name)
        columns=[]; keys=set()
        for column in table['columns']:
            key=ident(column['name'])
            if key in keys or column['type'] not in TYPES: raise ValueError('Invalid column')
            keys.add(key)
            columns.append(key+' '+column['type']+('' if column['nullable'] else ' NOT NULL')+(' DEFAULT '+column['default'] if 'default' in column else ''))
        if not set(table['primary_key'])<=keys: raise ValueError('Invalid primary key')
        columns += ['PRIMARY KEY ('+','.join(map(ident,table['primary_key']))+')']+table['constraints']
        ddl.append('CREATE TABLE photo.'+name+' (\n '+',\n '.join(columns)+'\n);')
        ddl += [i+';' for i in table['indexes']]
        expected=['SELECT','INSERT']+([] if table['append_only'] else ['UPDATE'])
        if table['acl']!={'photo_fn_owner':expected} or table['rls']!='force_trusted_functions':raise ValueError('Unexpected quota ACL')
        ddl += ['REVOKE ALL ON photo.'+name+' FROM PUBLIC;',
                'ALTER TABLE photo.'+name+' ENABLE ROW LEVEL SECURITY;',
                'ALTER TABLE photo.'+name+' FORCE ROW LEVEL SECURITY;',
                'CREATE POLICY billing_kernel ON photo.'+name+' TO photo_fn_owner USING (true) WITH CHECK (true);',
                'GRANT '+','.join(expected)+' ON photo.'+name+' TO photo_fn_owner;']
    ddl += ['CREATE POLICY billing_kernel_resources ON photo.billing_resource_types FOR SELECT TO photo_fn_owner USING (true);',
            'CREATE POLICY billing_kernel_admission ON photo.billing_admission_policies FOR SELECT TO photo_fn_owner USING (true);']
    body=(source/'quota-functions.sql').read_text()
    chunks=re.split(r'(?=CREATE FUNCTION photo\.)',body)
    code=[header,chunks[0]]
    parsed=[]
    for chunk in chunks[1:]:
        match=re.match(r'CREATE FUNCTION photo\.([a-z_]+)\(([^)]*)\)',chunk)
        if not match: raise ValueError('Invalid function declaration')
        name,args=match.groups()
        types=','.join(arg.strip().split()[1] for arg in args.split(',') if arg.strip())
        signature=name+'('+types+')'
        entry=next((f for f in functions['functions'] if f['signature']==signature),None)
        if entry is None or entry['owner']!='photo_fn_owner' or entry['execute_roles']!=[]: raise ValueError('Quota signature or ACL drift')
        if 'SECURITY DEFINER SET search_path=pg_catalog,photo' not in chunk:raise ValueError('Unsafe quota function')
        code += ['-- +goose StatementBegin\n'+chunk.strip()+'\n-- +goose StatementEnd',
                 'ALTER FUNCTION photo.'+signature+' OWNER TO photo_fn_owner;',
                 'REVOKE ALL ON FUNCTION photo.'+signature+' FROM PUBLIC;']
        parsed.append(signature)
    if set(parsed)!={f['signature'] for f in functions['functions']} or len(parsed)!=len(functions['functions']):raise ValueError('Function set mismatch')
    for table in catalog['tables']:
        if table['append_only']:
            code.append('CREATE TRIGGER billing_immutable BEFORE UPDATE OR DELETE ON photo.'+table['name']+' FOR EACH ROW EXECUTE FUNCTION photo.billing_quota_reject_immutable();')
    code.append('CREATE TRIGGER billing_budget_pin BEFORE UPDATE ON photo.billing_allowance_budgets FOR EACH ROW EXECUTE FUNCTION photo.billing_quota_pin_budget();')
    down="\n-- +goose Down\n-- +goose StatementBegin\nDO $$ BEGIN RAISE EXCEPTION 'Forward-only billing quota migration'; END $$;\n-- +goose StatementEnd\n"
    return {SCHEMA:'\n\n'.join(ddl)+down,FUNCTIONS:'\n\n'.join(code)+down}

def main():
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--check',action='store_true');args=p.parse_args()
    for name,content in render().items():
        path=ROOT/'backend/db/migrations'/name
        if args.check:
            if not path.exists() or path.read_text()!=content:raise SystemExit('Quota generated migration drift: '+name)
        else:path.write_text(content)
if __name__=='__main__':main()
