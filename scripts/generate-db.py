#!/usr/bin/env python3
"""Generate reproducible PostgreSQL DDL from the reviewed implementation catalog."""
from __future__ import annotations
import argparse
import json
import re
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]
TABLES=json.loads((ROOT/'docs/implementation/contracts/tables.json').read_text())['tables']
BY_NAME={t['name']:t for t in TABLES}
DEST=ROOT/'backend/db/migrations'
ROLES=['photo_api','photo_auth','photo_portal','photo_worker','photo_scheduler','photo_publisher','photo_maintenance','photo_fn_owner']
MIGRATIONS={1:'global_auth',2:'tenancy',3:'catalog',4:'ingest_sharing',5:'styles_snapshots',6:'workflow',7:'editor_review_bulk',8:'delivery',9:'lifecycle_import'}


def q(s):
    if not re.fullmatch('[a-z_][a-z_0-9]*',s):raise ValueError(s)
    return '"'+s+'"'


def column(spec):
    name,value=spec.split(':',1)
    if '=' in value:
        typ,default=value.split('=',1);nullable=False
        if typ in ['text','jsonb']:
            if default=="''":default=''
            default="'"+default.replace("'","''")+"'"+('::jsonb' if typ=='jsonb' else '')
        default=' DEFAULT '+default
    else:
        typ=value[:-1];nullable=value[-1]=='?';default=''
    if typ not in ['uuid','text','bytea','timestamptz','int','bigint','bool','jsonb']:raise ValueError(spec)
    return f'{q(name)} {typ}'+('' if nullable else ' NOT NULL')+default


def uniques(table):
    fields={'id','created_at'}|{c.split(':')[0] for c in table['columns']}
    if table['scope']=='tenant':fields.add('tenant_id')
    output=[]
    for group in re.findall(r'U\(([^)]+)\)',table['constraints']):
        columns=[{'job':'download_job_id','volume':'volume_no'}.get(c.strip(),c.strip()) for c in group.split(',')]
        if not set(columns)<=fields:raise ValueError((table['name'],columns,fields))
        # All tenant natural uniqueness includes tenant, except opaque globally unique token hashes.
        if table['scope']=='tenant' and 'tenant_id' not in columns and columns not in [['session_hash'],['token_hash']]:columns.insert(0,'tenant_id')
        output.append('UNIQUE ('+', '.join(map(q,columns))+')')
    return output


def generate():
    result={}
    for version,label in MIGRATIONS.items():
        lines=['-- Code generated by scripts/generate-db.py; DO NOT EDIT.','-- +goose Up']
        if version==1:
            lines+=['CREATE SCHEMA IF NOT EXISTS photo;','REVOKE CREATE ON SCHEMA public FROM PUBLIC;',
                    'REVOKE ALL ON SCHEMA photo FROM PUBLIC;', '-- +goose StatementBegin', 'DO $roles$ BEGIN']
            for role in ROLES:
                lines.append(f"IF NOT EXISTS (SELECT FROM pg_roles WHERE rolname='{role}') THEN CREATE ROLE {role} NOLOGIN NOBYPASSRLS; END IF;")
            lines+=['END $roles$;','-- +goose StatementEnd',f'GRANT USAGE ON SCHEMA photo TO {", ".join(ROLES)};']
        for t in [t for t in TABLES if int(t['migration'])==version]:
            cols=['id uuid PRIMARY KEY DEFAULT gen_random_uuid()','created_at timestamptz NOT NULL DEFAULT now()']
            if t['scope']=='tenant':cols+=['tenant_id uuid NOT NULL','UNIQUE(tenant_id,id)']
            cols += [column(c) for c in t['columns']]
            cols += uniques(t)
            for spec in t['columns']:
                name,typ=spec.split(':',1)
                if name=='revision' or name=='version_no':cols.append(f'CHECK ({q(name)}>0)')
                if name in ['bytes','storage_bytes','reserved_bytes','used_bytes','reserved_files','used_files','source_files','active_runs','active_gpu_tasks','scratch_bytes','ram_bytes','vram_bytes','item_count','files_done','bytes_written','expected_count']:
                    cols.append(f'CHECK ({q(name)}>=0)')
                if name in ['sha256','content_hash','config_hash','input_digest','result_digest','digest','profile_hash','input_sha256','source_sha256','source_manifest_hash','source_file_sha256','icc_sha256','request_hash','cache_key']:
                    cols.append(f"CHECK ({q(name)} ~ '^[0-9a-f]{{64}}$')")
            lines.append(f'CREATE TABLE photo.{q(t["name"])} (\n  '+',\n  '.join(cols)+'\n);')
            if t['scope']=='tenant':
                lines += [f'ALTER TABLE photo.{q(t["name"])} ENABLE ROW LEVEL SECURITY;',f'ALTER TABLE photo.{q(t["name"])} FORCE ROW LEVEL SECURITY;',
                  f"CREATE POLICY tenant_scope ON photo.{q(t['name'])} TO photo_api USING (tenant_id = nullif(current_setting('app.tenant_id', true),'')::uuid) WITH CHECK (tenant_id = nullif(current_setting('app.tenant_id', true),'')::uuid);",
                  f'CREATE POLICY trusted_functions ON photo.{q(t["name"])} TO photo_fn_owner USING (true) WITH CHECK (true);']
        lines+=['-- +goose Down',"-- Forward-only production migrations. Restore a backup for destructive rollback.","-- +goose StatementBegin","DO $$ BEGIN RAISE EXCEPTION 'Forward-only migration'; END $$;","-- +goose StatementEnd"]
        result[f'{version:05d}_{label}.sql']='\n\n'.join(lines)+'\n'
    return result


def main():
    parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args()
    for name,content in generate().items():
        dest=DEST/name
        if args.check:
            if not dest.exists() or dest.read_text()!=content:raise SystemExit(f'DDL drift: {dest}')
        else:dest.parent.mkdir(parents=True,exist_ok=True);dest.write_text(content)

if __name__=='__main__':main()
